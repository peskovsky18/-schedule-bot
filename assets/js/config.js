/**
 * Единственное, что нужно настроить после деплоя бота на Render.
 *
 * Укажите здесь адрес сервиса без слэша на конце, например:
 *   window.SCHEDULE_API_BASE = "https://schedule-bot-abc1.onrender.com";
 *
 * Если оставить пустым, мини-приложение будет обращаться к тому же
 * домену, с которого загружено (годится, если API и фронтенд на одном
 * хостинге).
 *
 * Адрес можно переопределить и без правки файла — параметром в ссылке:
 *   https://ваш-сайт.netlify.app/?api=https://schedule-bot-abc1.onrender.com
 */
/**
 * Название в шапке приложения.
 *
 * Раньше здесь стояли номер группы и институт — они длинные и занимали
 * две строки, а название группы всё равно одно и то же.
 */
window.APP = {
  title: "ППРСД super app",
};

window.SCHEDULE_API_BASE = "https://schedule-bot-umgq.onrender.com";

/**
 * Плеер: список треков, который можно слушать прямо в приложении.
 * Полоса плеера появляется внизу экрана, кнопка со списком открывает
 * выбор трека. Чтобы убрать плеер — enabled: false.
 *
 * Файлы лежат в assets/audio/. Имена держите из ASCII: пробелы,
 * кириллица и скобки в URL требуют кодирования и легко ломаются.
 *
 * preload="none": файл скачивается только когда человек нажмёт play,
 * поэтому общий вес дорожек не влияет на скорость открытия приложения.
 * Аудио отдаётся с обычным кэшем (сутки) — переслушивание бесплатно.
 *
 * Поддерживается и старый формат с одной дорожкой: вместо tracks
 * можно указать src и title.
 */
window.PLAYER = {
  enabled: true,

  tracks: [
    {
      title: "Voskresenskii — Франсе (prod. By Wipo)",
      src: "assets/audio/franse.mp3",
    },
    {
      title: "Voskresenskii — Стиралка (prod. By Wipo)",
      src: "assets/audio/stiralka.mp3",
    },
  ],

  // true — когда трек заканчивается, играет следующий.
  // По умолчанию выключено: трек просто останавливается.
  autoNext: false,

  // Начинать с того трека, который слушали в прошлый раз
  rememberLast: true,
};

/**
 * Рулетка «идти на пары или не идти». Живёт отдельным разделом в меню.
 *
 * enabled: false — убрать раздел целиком.
 *
 * Секторов может быть сколько угодно: колесо делится поровну, цвета
 * берутся из color, надписи внутри сектора — из short (title и symbol
 * показываются в результате после остановки).
 *
 * Выбор делает crypto.getRandomValues, а не Math.random: результат
 * не зависит от предыдущих прокруток.
 */
window.ROULETTE = {
  enabled: true,

  // Сколько миллисекунд крутится колесо
  spinMs: 2600,

  outcomes: [
    {
      symbol: "🎓",
      title: "Идти на пары",
      short: "Идти",
      tone: "go",
      color: "#2fb27c",
    },
    {
      symbol: "🛋️",
      title: "Не идти",
      short: "Не идти",
      tone: "skip",
      color: "#e0574f",
    },
  ],
};

