/**
 * Единственное, что нужно настроить после деплоя бота на Render.
 *
 * Укажите здесь адрес сервиса без слэша на конце, например:
 *   window.SCHEDULE_API_BASE = "https://schedule-bot-abc1.onrender.com";
 *
 * Если оставить пустым, мини-приложение будет обращаться к тому же
 * домену, с которого загружено (годится, если API и фронтенд на одном
 * хостинге).
 *
 * Адрес можно переопределить и без правки файла — параметром в ссылке:
 *   https://ваш-сайт.netlify.app/?api=https://schedule-bot-abc1.onrender.com
 */
window.SCHEDULE_API_BASE = "https://schedule-bot-umgq.onrender.com";

/**
 * Скример-розыгрыш: через некоторое время после открытия приложения
 * на весь экран появляется картинка, которую можно закрыть крестиком
 * или тапом в любом месте. Сама закрывается через durationMs.
 *
 * Чтобы выключить — поставьте enabled: false.
 *
 * Картинку положите в assets/img/scare.jpg (или укажите свой путь).
 * Совет по файлу: JPG, примерно 1080×1920, до 300 КБ — он загружается
 * заранее, чтобы появиться мгновенно, без задержки.
 *
 * Звука здесь нет намеренно: внезапный громкий звук может навредить
 * человеку с больным сердцем, а вспышки — спровоцировать приступ
 * у людей с фотосенситивной эпилепсией. Фотография с кнопкой
 * закрытия — безопасный уровень розыгрыша.
 */
window.SCREAMER = {
  enabled: true,
  delayMs: 30000, // через сколько показать (30 секунд)
  durationMs: 3000, // через сколько закрыть автоматически (3 секунды)
  image: "assets/img/scare.jpg",

  // Как вписывать картинку в экран:
  //   "cover"   — заполняет весь экран, но обрезает края по бокам;
  //   "contain" — видно фото целиком, сверху и снизу чёрные полосы.
  fit: "cover",
};

/**
 * Плеер: дорожка, которую можно включить прямо в приложении.
 * Полоса плеера появляется внизу экрана. Чтобы убрать — enabled: false.
 *
 * Файл лежит в assets/audio/. Имя держите из ASCII: пробелы, кириллица
 * и скобки в URL требуют кодирования и легко ломаются.
 *
 * preload="none": файл скачивается только когда человек нажмёт play,
 * поэтому вес дорожки не влияет на скорость открытия приложения.
 * Сам файл отдаётся с обычным кэшем (сутки) — переслушивание бесплатно.
 */
window.PLAYER = {
  enabled: true,
  src: "assets/audio/franse.mp3",
  title: "Voskresenskii — Франсе (prod. By Wipo)",
};
